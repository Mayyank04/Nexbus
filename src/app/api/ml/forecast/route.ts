import { NextResponse } from 'next/server';
import { getAdaptiveForecaster } from '@/lib/ml/adaptiveForecaster';

export async function POST(request: Request) {
  try {
    const body = await request.json();
    const { corridorId = 'corridor-ring-road', horizonMinutes = 30 } = body;

    const validHorizons = [15, 30, 45, 60];
    const horizon = validHorizons.includes(horizonMinutes) ? horizonMinutes : 30;

    const forecaster = getAdaptiveForecaster();
    const forecast = forecaster.generateForecast({
      corridorId,
      horizonMinutes: horizon as 15 | 30 | 45 | 60,
      featureTimestamp: new Date().toISOString(),
    });

    return NextResponse.json({
      success: true,
      forecast,
      advisoryDisclaimer:
        'Model prediction represents a statistical estimate generated by the adaptive forecasting engine. It does not control vehicle dispatch.',
      timestamp: new Date().toISOString(),
    });
  } catch (err: any) {
    return NextResponse.json(
      { success: false, error: err.message || 'Failed to generate forecast' },
      { status: 400 }
    );
  }
}
